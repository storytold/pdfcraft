//! Dialogs for hybrid bookmark auto-generation, regex hierarchy nesting, and page shifting.

use pdfcraft_engine::{DocId, Edit};

use crate::theme::{self, Tokens};
use crate::{PdfCraftApp, widgets};

/// Draft state for Bookmarks ▸ Auto-generate bookmarks.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AutoGenerateDraft {
    pub doc: Option<DocId>,
    pub max_depth: u8,
    pub prefer_toc: bool,
    pub replace_existing: bool,
}

impl Default for AutoGenerateDraft {
    fn default() -> Self {
        Self { doc: None, max_depth: 3, prefer_toc: true, replace_existing: true }
    }
}

/// Draft state for Bookmarks ▸ Nest bookmarks by numbering.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RegexNestDraft {
    pub doc: Option<DocId>,
    pub use_custom: bool,
    pub pattern: String,
}

impl Default for RegexNestDraft {
    fn default() -> Self {
        Self { doc: None, use_custom: false, pattern: pdfcraft_engine::DEFAULT_REGEX_NEST_PATTERN.to_string() }
    }
}

/// Draft state for Bookmarks ▸ Shift bookmark pages.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ShiftPagesDraft {
    pub doc: Option<DocId>,
    pub paths: Vec<Vec<usize>>,
    pub include_children: bool,
    pub page_delta: i32,
}

impl Default for ShiftPagesDraft {
    fn default() -> Self {
        Self { doc: None, paths: Vec::new(), include_children: true, page_delta: 1 }
    }
}

pub(crate) fn auto_generate_body(ui: &mut egui::Ui, app: &mut PdfCraftApp, t: &Tokens) -> bool {
    ui.label(egui::RichText::new(tl!("Auto-generate bookmarks")).font(theme::semibold(18.0)));
    ui.add_space(6.0);
    ui.label(
        egui::RichText::new(tl!("Reads a Table of Contents page or analyses heading sizes and weights across the document.")).color(t.text_muted),
    );
    ui.add_space(10.0);
    let d = &mut app.auto_generate_draft;
    let doc_id = d.doc;
    ui.horizontal(|ui| {
        ui.label(tl!("Maximum heading levels"));
        ui.add(egui::DragValue::new(&mut d.max_depth).range(1..=6));
    });
    ui.add(crate::widgets::checkbox(&mut d.prefer_toc, tl!("Prefer Table of Contents page when found")));
    ui.add(crate::widgets::checkbox(&mut d.replace_existing, tl!("Replace existing bookmarks")));
    let opts = (d.max_depth, d.prefer_toc, d.replace_existing);
    ui.add_space(14.0);
    let mut close = false;
    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
        if widgets::pill_button(ui, tl!("Generate"), true).clicked() {
            close = true;
            if let Some(i) = doc_id.and_then(|id| app.views.iter().position(|v| v.id == id)) {
                app.active = Some(i);
                if app.apply_edit(Edit::AutoGenerateBookmarks { max_depth: opts.0, prefer_toc: opts.1, replace_existing: opts.2 }) {
                    app.right = Some(crate::RightPanel::Bookmarks);
                }
            }
        }
        if widgets::pill_button(ui, tl!("Cancel"), false).clicked() {
            close = true;
        }
    });
    close
}

pub(crate) fn regex_nest_body(ui: &mut egui::Ui, app: &mut PdfCraftApp, t: &Tokens) -> bool {
    ui.label(egui::RichText::new(tl!("Nest bookmarks by numbering")).font(theme::semibold(18.0)));
    ui.add_space(6.0);
    ui.label(egui::RichText::new(tl!("Organizes existing bookmarks by numbered section prefixes such as 1, 1.1, 1.1.1.")).color(t.text_muted));
    ui.add_space(10.0);
    let d = &mut app.regex_nest_draft;
    let doc_id = d.doc;
    ui.add(crate::widgets::checkbox(&mut d.use_custom, tl!("Use custom regular expression")));
    ui.add_enabled_ui(d.use_custom, |ui| {
        ui.add(crate::widgets::line(&mut d.pattern).desired_width(400.0));
    });
    let pattern = d.use_custom.then(|| d.pattern.clone());
    ui.add_space(14.0);
    let mut close = false;
    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
        if widgets::pill_button(ui, tl!("Apply"), true).clicked() {
            close = true;
            if let Some(i) = doc_id.and_then(|id| app.views.iter().position(|v| v.id == id)) {
                app.active = Some(i);
                app.apply_edit(Edit::RegexNestBookmarks { pattern });
            }
        }
        if widgets::pill_button(ui, tl!("Cancel"), false).clicked() {
            close = true;
        }
    });
    close
}

pub(crate) fn shift_pages_body(ui: &mut egui::Ui, app: &mut PdfCraftApp, t: &Tokens) -> bool {
    ui.label(egui::RichText::new(tl!("Shift bookmark pages")).font(theme::semibold(18.0)));
    ui.add_space(6.0);
    ui.label(egui::RichText::new(tl!("Adjusts destination page numbers forward or backward for selected bookmarks.")).color(t.text_muted));
    ui.add_space(10.0);
    let d = &mut app.shift_pages_draft;
    let doc_id = d.doc;
    ui.horizontal(|ui| {
        ui.label(tl!("Page offset"));
        ui.add(egui::DragValue::new(&mut d.page_delta).range(-10_000..=10_000));
    });
    ui.add(crate::widgets::checkbox(&mut d.include_children, tl!("Include child bookmarks")));
    let count = d.paths.len();
    ui.label(egui::RichText::new(format!("{count} selected bookmark(s)")).color(t.text_faint));
    let args = (d.paths.clone(), d.include_children, d.page_delta);
    ui.add_space(14.0);
    let mut close = false;
    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
        if ui.add_enabled_ui(!args.0.is_empty(), |ui| widgets::pill_button(ui, tl!("Apply"), true)).inner.clicked() {
            close = true;
            if let Some(i) = doc_id.and_then(|id| app.views.iter().position(|v| v.id == id)) {
                app.active = Some(i);
                app.apply_edit(Edit::ShiftBookmarkPages { paths: args.0, include_children: args.1, page_delta: args.2 });
            }
        }
        if widgets::pill_button(ui, tl!("Cancel"), false).clicked() {
            close = true;
        }
    });
    close
}
