//! pdfcraft-arlington — structural validation of a PDF's object graph against the Arlington PDF
//! Model, the PDF Association's machine-readable form of ISO 32000-2.
//!
//! The model describes every dictionary and array a PDF can hold: its keys, their types, whether
//! they are required, the values they may take, the PDF version each appeared in or was
//! deprecated in, and whether a value must be a direct object or an indirect reference.
//! [`validate`] walks the document from the trailer, works out each object's model type from the
//! key that leads to it, and reports where the document departs from the model.
//!
//! - **Standalone (L0).** No other PdfCraft crate: the caller hands the document over through
//!   [`Source`], so this crate never parses a file. The engine adapts its object layer to it.
//! - **Honest.** Rules written as predicates the validator doesn't implement are counted in
//!   [`Report::not_checked`], never guessed. An object no model type fits is reported as such
//!   and not checked further, rather than checked against a wrong type.
//! - **Bounded.** A seen-set stops cycles, and [`Options`] caps the objects visited, the
//!   findings kept and the nesting followed. Every input is untrusted: nothing here panics.
//!
//! The model data is the committed table `data/arlington.tsv`, generated by
//! `cargo xtask arlington` from a pinned commit of the model (Apache-2.0, see `ATTRIBUTION.toml`).

#![deny(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::unimplemented, clippy::todo, clippy::unreachable)]

