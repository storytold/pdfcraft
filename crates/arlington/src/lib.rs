pub const MODEL_COMMIT: &str = "d37f4c8b11f54ae0d81a278bdeb91d00d6ccde26";

/// An indirect reference: object number and generation.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Ref {
    pub num: u32,
    pub generation: u16,
}

impl std::fmt::Display for Ref {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{} {} R", self.num, self.generation)
    }
}

/// A PDF object as the validator sees it: direct objects nested, indirect ones as [`Ref`].
#[derive(Clone, Debug, PartialEq)]
pub enum Object {
    Null,
    Bool(bool),
    Int(i64),
    Real(f64),
    /// A string; `hex` says it was written `<…>`.
    String {
        bytes: Vec<u8>,
        hex: bool,
    },
    Name(Vec<u8>),
    Array(Vec<Object>),
    /// A dictionary, keys in file order.
    Dict(Vec<(Vec<u8>, Object)>),
    /// A stream's dictionary (the data is never needed).
    Stream(Vec<(Vec<u8>, Object)>),
    Ref(Ref),
}

impl Object {
    /// The dictionary entries of a dictionary or stream.
    pub fn entries(&self) -> Option<&[(Vec<u8>, Object)]> {
        match self {
            Object::Dict(d) | Object::Stream(d) => Some(d),
            _ => None,
        }
    }

    /// The value of `key` in a dictionary or stream.
    pub fn get(&self, key: &[u8]) -> Option<&Object> {
        self.entries()?.iter().find(|(k, _)| k.as_slice() == key).map(|(_, v)| v)
    }
}

/// The document being validated.
pub trait Source {
    /// The trailer dictionary (for a file with cross-reference streams, the merged trailer).
    fn trailer(&self) -> Object;
    /// An indirect object, or `None` when it does not exist (free, missing or unreadable).
    fn get(&self, r: Ref) -> Option<Object>;
    /// The version in the file header (`%PDF-1.7`).
    fn header_version(&self) -> Option<Version>;
    /// The file's length in bytes, for `fn:FileSize()`.
    fn file_size(&self) -> Option<u64> {
        None
    }
    /// The 0-based page index of a page object, so findings can point at their page.
    fn page_index(&self, _r: Ref) -> Option<usize> {
        None
    }
    /// The number of pages, for `fn:NumberOfPages()`.
    fn page_count(&self) -> Option<usize> {
        None
    }
}

/// Limits on one validation. The defaults keep a large document to a few seconds.
#[derive(Clone, Debug, PartialEq)]
pub struct Options {
    /// Objects (direct and indirect) checked before the walk stops.
    pub max_objects: usize,
    /// Findings kept per severity; the totals go on counting.
    pub max_findings: usize,
    /// Report keys the model doesn't define ([`Severity::Info`]).
    pub unknown_keys: bool,
}

impl Default for Options {
    fn default() -> Self {
        Options { max_objects: 200_000, max_findings: 1_000, unknown_keys: true }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Severity {
    /// The document breaks a rule of the model ("shall").
    Error,
    /// Allowed, but out of place: newer than the file's version, deprecated, or not identifiable.
    Warning,
    /// Not in the model, which the specification allows (second-class and private keys).
    Info,
}

impl Severity {
    pub fn id(self) -> &'static str {
        match self {
            Severity::Error => "error",
            Severity::Warning => "warning",
            Severity::Info => "info",
        }
    }
}

/// What a finding is about.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Rule {
    /// A required key or array element is missing.
    Required,
    /// A value of a type the model doesn't allow there.
    Type,
    /// A value the model doesn't allow there.
    Value,
    /// A value that must be an indirect reference is direct.
    Indirect,
    /// A value that must be direct is an indirect reference.
    Direct,
    /// Introduced in a later PDF version than the file's.
    Version,
    /// Deprecated in the file's PDF version.
    Deprecated,
    /// A special-case rule of the model does not hold.
    Condition,
    /// An array with too many elements, or not in whole sets.
    ArrayLength,
    /// A reference to an object that does not exist.
    MissingObject,
    /// No model type fits the object.
    UnknownType,
    /// A key the model doesn't define for this type.
    UnknownKey,
}

impl Rule {
    pub fn id(self) -> &'static str {
        match self {
            Rule::Required => "required",
            Rule::Type => "type",
            Rule::Value => "value",
            Rule::Indirect => "indirect",
            Rule::Direct => "direct",
            Rule::Version => "version",
            Rule::Deprecated => "deprecated",
            Rule::Condition => "condition",
            Rule::ArrayLength => "array-length",
            Rule::MissingObject => "missing-object",
            Rule::UnknownType => "unknown-type",
            Rule::UnknownKey => "unknown-key",
        }
    }
}

/// How an interface says one of the [`WORDINGS`] in its own language: given the English wording,
/// the wording in that language. [`in_english`] keeps the English.
pub type Words<'a> = &'a dyn Fn(&str) -> String;

/// The [`Words`] that translate nothing.
pub fn in_english(wording: &str) -> String {
    wording.to_owned()
}

/// Every sentence a finding can say, with named holes (`{key}`, `{type}`, …) for the document's
/// own words. An interface translates these and fills the holes with [`Finding::said`].
pub const WORDINGS: &[&str] = &[
    check::W_REQUIRED,
    check::W_TYPE,
    check::W_VALUE,
    check::W_VALUE_RULE,
    check::W_REQUIRED_VALUE,
    check::W_INDIRECT,
    check::W_DIRECT,
    check::W_SINCE,
    check::W_DEPRECATED,
    check::W_VALUE_SINCE,
    check::W_VALUE_DEPRECATED,
    check::W_TYPE_SINCE,
    check::W_CONDITION,
    check::W_TOO_MANY,
    check::W_SETS,
    check::W_MISSING_OBJECT,
    check::W_NO_TYPE,
    check::W_UNKNOWN_KEY,
];

/// One place where the document departs from the model.
#[derive(Clone, Debug, PartialEq)]
pub struct Finding {
    pub severity: Severity,
    pub rule: Rule,
    /// The indirect object that holds the problem (the nearest one, for a direct value).
    pub object: Option<Ref>,
    /// The 0-based page the object belongs to, when it is on a page.
    pub page: Option<usize>,
    /// The annotation rectangle, when the object holding the problem is an annotation.
    pub rect: Option<[f64; 4]>,
    /// Where the walk found it, from the trailer: `trailer/Root/Pages/Kids/0`.
    pub path: String,
    /// The model type of the object holding the problem.
    pub type_name: String,
    /// The key or array index the finding is about (empty for the object as a whole).
    pub key: String,
    wording: &'static str,
    args: Vec<(&'static str, String)>,
}

impl Finding {
    /// The English wording with its holes, one of [`WORDINGS`].
    pub fn wording(&self) -> &'static str {
        self.wording
    }

    /// The finding said through `words`, holes filled with the document's own words.
    pub fn said(&self, words: Words) -> String {
        let mut s = words(self.wording);
        for (hole, value) in &self.args {
            s = s.replace(&format!("{{{hole}}}"), value);
        }
        s
    }

    /// The finding in English.
    pub fn message(&self) -> String {
        self.said(&in_english)
    }
}

/// The result of [`validate`].
#[derive(Clone, Debug, PartialEq)]
pub struct Report {
    /// The version the document was checked against: the header's, or the catalog's
    /// `/Version` when that is later (ISO 32000-2 §7.2.2).
    pub version: Version,
    /// `true` when neither said a version and 2.0 was assumed.
    pub version_assumed: bool,
    /// Findings, errors first, then warnings, then the rest, each in the order the walk met them.
    pub findings: Vec<Finding>,
    /// How many findings of each severity there were, including any past the cap.
    pub errors: usize,
    pub warnings: usize,
    pub infos: usize,
    /// Objects checked (direct and indirect).
    pub objects: usize,
    /// Rules the validator could not evaluate, by predicate (`InNameTree`, `Extension`, …), with
    /// how many times one was met. These were neither passed nor failed.
    pub not_checked: Vec<(String, usize)>,
    /// The walk stopped at [`Options::max_objects`]; the rest of the document wasn't checked.
    pub stopped_early: bool,
    /// Some findings were left out at [`Options::max_findings`].
    pub truncated: bool,
}

impl Report {
    pub fn count(&self, s: Severity) -> usize {
        match s {
            Severity::Error => self.errors,
            Severity::Warning => self.warnings,
            Severity::Info => self.infos,
        }
    }

    /// No errors (warnings and information aside).
    pub fn is_valid(&self) -> bool {
        self.errors == 0
    }
}

/// A [`Source`] held in memory: for tests, fuzzing, and callers that already have the objects.
#[derive(Clone, Debug, Default)]
pub struct MemSource {
    pub trailer: Vec<(Vec<u8>, Object)>,
    pub objects: std::collections::HashMap<u32, Object>,
    pub version: Option<Version>,
    pub pages: Vec<Ref>,
}

impl Source for MemSource {
    fn trailer(&self) -> Object {
        Object::Dict(self.trailer.clone())
    }

    fn get(&self, r: Ref) -> Option<Object> {
        self.objects.get(&r.num).cloned()
    }

    fn header_version(&self) -> Option<Version> {
        self.version
    }

    fn page_index(&self, r: Ref) -> Option<usize> {
        self.pages.iter().position(|p| p.num == r.num)
    }

    fn page_count(&self) -> Option<usize> {
        Some(self.pages.len())
    }
}

