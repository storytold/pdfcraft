//! JPEG XL image XObjects (`/Filter /JXLDecode`, vendored hayro-syntax patch 29, #4782).
//!
//! The two images are the 256 x 128 synthetic gradient of [`pixel`], written by libjxl's `cjxl`:
//! once lossless (`-d 0`), and once as the lossless recompression of a q90 JPEG of it (which
//! `djxl` reconstructs byte for byte). Nothing in them is third-party.

use crate::{PageRenderer, RenderConfig, RenderRequest, RenderedPage, RequestKind};
use std::io::Write;
use std::sync::Arc;

const W: usize = 256;
const H: usize = 128;

/// Sample (`x`, `y`) of the test image: a colour gradient, a dark bar and a checker block.
fn pixel(x: usize, y: usize) -> [u8; 3] {
    let (mut r, mut g, mut b) = (x as u8, (y * 2) as u8, (255 - x) as u8);
    if (40..56).contains(&y) {
        (r, g, b) = (20, 20, 20);
    }
    if x >= 192 && y >= 64 && (x / 8 + y / 8).is_multiple_of(2) {
        (r, g, b) = (250, 250, 250);
    }
    [r, g, b]
}

fn raw_rgb() -> Vec<u8> {
    (0..H).flat_map(|y| (0..W).flat_map(move |x| pixel(x, y))).collect()
}

/// A one-page PDF (256 x 128 pt) drawing one RGB image whose stream is `data` under `filter`.
fn pdf(filter: &str, data: &[u8], width: usize) -> Vec<u8> {
    let content = b"q 256 0 0 128 0 0 cm /Im0 Do Q";
    let mut out = b"%PDF-1.7\n1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n\
3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 256 128] /Contents 4 0 R /Resources << /XObject << /Im0 5 0 R >> >> >> endobj\n"
        .to_vec();
    out.extend_from_slice(format!("4 0 obj << /Length {} >> stream\n", content.len()).as_bytes());
    out.extend_from_slice(content);
    out.extend_from_slice(b"\nendstream endobj\n");
    out.extend_from_slice(
        format!(
            "5 0 obj << /Type /XObject /Subtype /Image /Width {width} /Height {H} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /{filter} /Length {} >> stream\n",
            data.len()
        )
        .as_bytes(),
    );
    out.extend_from_slice(data);
    out.extend_from_slice(b"\nendstream endobj\ntrailer << /Root 1 0 R >>\n%%EOF");
    out
}

fn render(pdf: Vec<u8>) -> RenderedPage {
    let mut r = PageRenderer::new(Arc::new(pdf), RenderConfig::default());
    let page = r.render(RenderRequest { page: 0, kind: RequestKind::Pixels, tile: None, scale: 1.0, tag: 0, preview: false });
    assert!(page.error.is_none(), "{:?}", page.error);
    assert_eq!((page.width as usize, page.height as usize), (W, H));
    page
}

/// The same pixels in Flate: what a JPEG XL page must draw like.
fn flate_page() -> RenderedPage {
    let mut z = flate2::write::ZlibEncoder::new(Vec::new(), flate2::Compression::default());
    z.write_all(&raw_rgb()).unwrap();
    render(pdf("FlateDecode", &z.finish().unwrap(), W))
}

/// (mean, largest) absolute difference over the RGB channels.
fn diff(a: &RenderedPage, b: &RenderedPage) -> (f64, u8) {
    let (mut sum, mut max, mut n) = (0u64, 0u8, 0u64);
    for (p, q) in a.rgba.chunks(4).zip(b.rgba.chunks(4)) {
        for i in 0..3 {
            let d = p[i].abs_diff(q[i]);
            sum += u64::from(d);
            max = max.max(d);
            n += 1;
        }
    }
    (sum as f64 / n as f64, max)
}

#[test]
fn a_lossless_jxl_image_draws_exactly_like_the_same_pixels_in_flate() {
    let (mean, max) = diff(&flate_page(), &render(pdf("JXLDecode", LOSSLESS, W)));
    assert_eq!((mean, max), (0.0, 0), "lossless JPEG XL is pixel-exact");
}

#[test]
fn a_jpeg_recompressed_to_jxl_draws_like_that_jpeg() {
    // The pixels are the q90 JPEG's, not the original's: only the JPEG's own loss is allowed.
    let (mean, max) = diff(&flate_page(), &render(pdf("JXLDecode", FROM_JPEG, W)));
    assert!(mean < 3.0 && max < 80, "mean {mean}, max {max}");
}

#[test]
fn a_jxl_image_whose_size_disagrees_with_its_dictionary_is_not_drawn() {
    // The dictionary says 128 wide; the codestream is 256: neither is trusted, the page stays white.
    let page = render(pdf("JXLDecode", LOSSLESS, W / 2));
    assert!(page.rgba.chunks(4).all(|p| p[..3] == [255, 255, 255]));
}

#[test]
fn damaged_jxl_data_draws_nothing_and_does_not_end_the_page() {
    for data in [&LOSSLESS[..LOSSLESS.len() / 2], &[0xff, 0x0a, 0x00][..], &[][..]] {
        let page = render(pdf("JXLDecode", data, W));
        assert!(page.rgba.chunks(4).all(|p| p[..3] == [255, 255, 255]), "{} bytes", data.len());
    }
}

