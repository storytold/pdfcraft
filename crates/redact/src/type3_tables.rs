//! Predefined font encodings (ISO 32000 Annex D) mapping character codes to glyph names.

//! Each encoding lists only the codes it maps; every other code is unmapped.

type Entries = &'static [(u8, &'static [u8])];

const fn build(entries: Entries) -> [Option<&'static [u8]>; 256] {
    let mut out: [Option<&'static [u8]>; 256] = [None; 256];
    let mut i = 0;
    while i < entries.len() {
        out[entries[i].0 as usize] = Some(entries[i].1);
        i += 1;
    }
    out
}

