#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn hot_folder_seven_catalogs_are_complete_and_system_defaults_are_deterministic() {
        let keys: std::collections::BTreeSet<_> = MESSAGES.iter().map(|row| row[0]).collect();
        assert_eq!(keys.len(), MESSAGES.len(), "duplicate translation keys");
        for row in MESSAGES {
            assert!(row.iter().all(|text| !text.is_empty()));
        }
        let source = concat!(include_str!("ui.rs"), include_str!("source_ui.rs"));
        for (at, _) in source.match_indices("t(\"") {
            if source.get(..at).and_then(|s| s.chars().last()).is_some_and(|c| c.is_alphanumeric() || c == '_') {
                continue;
            }
            let suffix = source.get(at + 3..).unwrap();
            let key = suffix.split('"').next().unwrap();
            assert!(keys.contains(key), "missing translation: {key}");
        }
        for (locale, index) in [("de-AT", 1), ("fr-CA", 2), ("nl-NL", 3), ("es-ES", 4), ("no-NO", 5), ("sv-SE", 6), ("ja-JP", 0)] {
            assert_eq!(Language::system(Some(locale)), Language(index));
        }
    }
}
