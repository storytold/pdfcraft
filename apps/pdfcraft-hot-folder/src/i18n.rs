#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Language(pub usize);

impl Language {
    pub fn system(locale: Option<&str>) -> Self {
        let code = pdfcraft_engine::ocr::language_for_locale(locale);
        Self(LANGUAGES.iter().position(|l| l.0 == code).unwrap_or(0))
    }
    pub fn t(self, key: &'static str) -> &'static str {
        MESSAGES.iter().find(|row| row[0] == key).and_then(|row| row.get(self.0)).copied().unwrap_or(key)
    }
}

